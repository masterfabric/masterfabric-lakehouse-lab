"""Run the showcase queries on Trino (the Impala stand-in) and save results + timings.

Writes docs/results/trino_queries.json and docs/results/trino_queries.md.
Requires the stack to be up and the pipeline to have run (`make up pipeline`).
"""

from __future__ import annotations

import json
import os
import time
from pathlib import Path

import trino

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "results"

QUERIES = {
    "congestion_backlog": """
        SELECT upgrade_priority, count(*) AS cells, round(avg(p95_utilization), 3) AS avg_p95_utilization,
               sum(congested_hours) AS congested_hours
        FROM lake.gold.cell_congestion_ranking GROUP BY 1 ORDER BY 1""",
    "busiest_cities_evening_peak": """
        SELECT city, round(avg(utilization), 3) AS avg_util_19_22h, count_if(is_congested) AS congested_cell_hours
        FROM lake.gold.cell_hourly_load WHERE hour(hour_ts) BETWEEN 19 AND 22
        GROUP BY 1 ORDER BY 2 DESC LIMIT 5""",
    "usage_by_segment": """
        SELECT segment, count(DISTINCT subscriber_id) AS subscribers,
               round(sum(voice_minutes) / count(DISTINCT subscriber_id), 1) AS minutes_per_sub,
               round(sum(data_mb) / count(DISTINCT subscriber_id) / 1024, 2) AS gb_per_sub,
               round(sum(dropped_calls) * 100.0 / nullif(sum(voice_calls), 0), 2) AS drop_pct
        FROM lake.gold.daily_subscriber_usage GROUP BY 1 ORDER BY 3 DESC""",
    "quarantine_by_reason": """
        SELECT feed, reason, count(*) AS records FROM lake.silver.quarantine GROUP BY 1, 2 ORDER BY 3 DESC""",
    # The gold usage mart was rebuilt after the correction feed: compare its first snapshot with
    # the current one. {oldest} is resolved first because FOR VERSION AS OF needs a constant.
    "time_travel_in_trino": """
        SELECT 'first build (snapshot {oldest})' AS version, count(*) AS subscriber_days,
               sum(voice_calls) AS voice_calls, sum(charge_try) AS charge_try
        FROM lake.gold.daily_subscriber_usage FOR VERSION AS OF {oldest}
        UNION ALL
        SELECT 'current (after corrections)', count(*), sum(voice_calls), sum(charge_try)
        FROM lake.gold.daily_subscriber_usage""",
    "dq_history": """
        SELECT date_format(run_at, '%Y-%m-%d %H:%i') AS run, count(*) AS rules, count_if(passed) AS passed
        FROM lake.ops.dq_results GROUP BY 1 ORDER BY 1""",
    "churn_score_deciles": """
        SELECT ntile AS decile, count(*) AS subscribers, round(avg(churn_risk_score), 3) AS avg_score,
               round(avg(usage_trend), 3) AS avg_usage_trend
        FROM (SELECT *, ntile(10) OVER (ORDER BY churn_risk_score DESC) AS ntile FROM lake.gold.churn_features)
        GROUP BY 1 ORDER BY 1""",
}


def md_table(cols, rows) -> str:
    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "".join("| " + " | ".join(str(v) for v in r) + " |\n" for r in rows)


def main() -> None:
    conn = trino.dbapi.connect(host="127.0.0.1", port=int(os.environ.get("PORT_TRINO", 18080)),
                               user="lab", catalog="lake")
    cur = conn.cursor()
    results, md = {}, ["# Trino query results\n\nGenerated by `make trino-sql` against the live lab.\n"]
    cur.execute('SELECT min_by(snapshot_id, committed_at) FROM lake.gold."daily_subscriber_usage$snapshots"')
    oldest = cur.fetchall()[0][0]
    for name, sql in QUERIES.items():
        sql = sql.replace("{oldest}", str(oldest))
        cur.execute(sql)
        cur.fetchall()  # warm-up: metadata and file footers cached
        t0 = time.perf_counter()
        cur.execute(sql)
        rows = cur.fetchall()
        ms = round((time.perf_counter() - t0) * 1000, 1)
        cols = [d[0] for d in cur.description]
        rows = [[str(v) if not isinstance(v, (int, float)) else v for v in r] for r in rows]
        results[name] = {"sql": " ".join(sql.split()), "columns": cols, "rows": rows, "warm_ms": ms}
        md.append(f"## {name} ({ms} ms warm)\n\n```sql\n{sql.strip()}\n```\n\n{md_table(cols, rows)}\n")
        print(f"[trino] {name}: {len(rows)} rows, {ms} ms")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "trino_queries.json").write_text(json.dumps(results, indent=2) + "\n")
    (OUT / "trino_queries.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
